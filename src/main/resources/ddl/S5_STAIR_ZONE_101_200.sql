-- Season 5 - "stair zone" floors 101-200 (2026-09-28).
--
-- Request: from floor 101 each floor is a fixed 9-tile board
--   STAIRS - COMBAT - COMBAT - LUCKY(random) - MIDBOSS - COMBAT - COMBAT - LUCKY(random) - MIDBOSS
-- with linear (gentler) monster scaling, staircase map. The tile ORDER itself
-- lives in code (BotS5ServiceImpl.STAIR_ZONE_PATTERN, not shuffled); this script
-- only seeds the two tables the code reads per floor:
--
--   1) TBOT_S5_FLOOR_INFO      : TILE_COUNT = 9 for floors 101-200.
--   2) TBOT_S5_MONSTER_INFO_V2 : one normal (BOSS_YN='N') row per floor 101-200.
--      The stair zone has no boss floors -- the two MIDBOSS tiles reuse this row
--      with the existing mid-boss x3 multiplier, so no boss rows are needed.
--      Monster name / PP_PER_KILL come from block 10's TBOT_S5_MONSTER_INFO row
--      (BotS5ServiceImpl.monsterBlockNo caps the block at 10).
--
-- Formulas ("make the slope a bit gentler" -- user confirmed): continue the
-- currently LIVE 1-99 linear curves from floor 100 with HALF the slope.
--   live normal HP  = (420 + 1304*(f-1)) * (2.5/4.5)   [S5_BALANCE_V2_K_REDUCTION]
--   live normal ATK = 6 + 1.85*(f-1)
--   live DEF        = 61-99 ramp 100 -> 6096 (BotS5ServiceImpl.monsterDefForFloor)
--   floor >= 101:
--     HP  = 71953.3 + 362.22 * (f-100)
--     ATK = 189.15  + 0.925  * (f-100)
--     DEF = 6096    + 78.895 * (f-99)   (code computes DEF itself via
--           monsterDefForFloor; the DEF_VALUE column here is informational only,
--           same as for floors 51-99)
--   samples: 101 = 72316 / 190 / 6254,  150 = 90064 / 235 / 10120,
--            200 = 108176 / 282 / 14064
-- ATK boost (x1.4 for floor>50) and investAtkScale are applied on top in code,
-- exactly like floors 51-99.
--
-- Safe to re-run: deletes this range first. ASCII-only file.
-- Nothing reads these rows until the matching code is deployed (the live code
-- still blocks floors >= 100 via CONTENT_LOCKED_FLOOR).
-- ============================================================

