-- Season 5 - live DB migration: split companion name pool by GRADE (star tier).
--
-- Root cause of the "already-owned name pulled again at a higher grade just
-- evaporates" bug (confirmed live case reported by a user: owned a GRADE=2
-- ARCHER companion, pulled a GRADE=3 ARCHER that happened to roll the exact
-- same name, got refunded 20% PP instead of a new companion): names used to
-- be shared across ALL grades (3 names per job, grade-independent), so the
-- same name could appear at two different grades and collide with the "same
-- job+name = duplicate" check. The application code (BotS5ServiceImpl) now
-- uses NAME_POOL_BY_JOB_GRADE -- grade 1 keeps the original 15 names, grades
-- 2-6 get brand new non-overlapping names (2x3 + 3x3 + 4x2 + 5x1 + 6x1 = 13
-- per job, 65 total) -- so a name now always implies its grade and this class
-- of bug can no longer happen going forward.
--
-- This script only fixes EXISTING data: every companion currently at GRADE>=2
-- still carries an old grade-independent name (one of the original 15 names,
-- which are now GRADE=1-only) and needs to be renamed to a name from its own
-- grade's new pool. GRADE=1 rows are untouched (grade 1
-- pool is unchanged). Names are Korean but this file is pure ASCII -- every
-- literal goes in as CP949 (KO16MSWIN949) bytes via HEXTORAW per CLAUDE.md's
-- encoding rule, never as a literal Korean character in the .sql file itself.
--
-- Assignment rule: for each (USER_NAME, CLASS, GRADE) group, existing rows are
-- numbered by COMPANION_ID and cycled through that grade's name pool (MOD),
-- so within one user's own roster the new names differ as long as they don't
-- already own more same-class-same-grade companions than that tier's pool
-- size (checked against live data before writing this script -- max 2 seen,
-- well under the smallest pool size of 3 for grades 2-3; grades 4-6 have no
-- existing rows at all yet). Reuse of a name across DIFFERENT users is fine
-- and expected (same as the original shared-pool design).
--
-- Safe to re-run (idempotent: recomputes the same deterministic assignment
-- each time, no accumulating side effects).
-- ============================================================

MERGE INTO TBOT_S5_USER_COMPANION C
USING (
    SELECT R.COMPANION_ID, NP.NM AS NEW_NAME
    FROM (
        SELECT COMPANION_ID, CLASS, GRADE,
               MOD(
                   ROW_NUMBER() OVER (PARTITION BY USER_NAME, CLASS, GRADE ORDER BY COMPANION_ID) - 1,
                   CASE GRADE WHEN 4 THEN 2 WHEN 5 THEN 1 WHEN 6 THEN 1 ELSE 3 END
               ) AS IDX
        FROM TBOT_S5_USER_COMPANION
        WHERE GRADE >= 2
    ) R
    JOIN (
        -- name pool for grades 2-6, generated from NAME_POOL_BY_JOB_GRADE (grade 1 pool unchanged, not included here)
        SELECT 'WARRIOR' CLASS, 2 GRADE, 0 IDX, UTL_RAW.CAST_TO_VARCHAR2(HEXTORAW('C4CBB0ED')) NM FROM DUAL UNION ALL
