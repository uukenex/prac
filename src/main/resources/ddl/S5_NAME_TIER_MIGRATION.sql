        SELECT 'PRIEST' CLASS, 2 GRADE, 0 IDX, UTL_RAW.CAST_TO_VARCHAR2(HEXTORAW('B8F0B8F0C4AB')) NM FROM DUAL UNION ALL
        SELECT 'PRIEST' CLASS, 2 GRADE, 1 IDX, UTL_RAW.CAST_TO_VARCHAR2(HEXTORAW('C0CCBFC0B8AE')) NM FROM DUAL UNION ALL
        SELECT 'PRIEST' CLASS, 2 GRADE, 2 IDX, UTL_RAW.CAST_TO_VARCHAR2(HEXTORAW('BDC3BFC2')) NM FROM DUAL UNION ALL
        SELECT 'PRIEST' CLASS, 3 GRADE, 0 IDX, UTL_RAW.CAST_TO_VARCHAR2(HEXTORAW('B3EBC1B6B9CC')) NM FROM DUAL UNION ALL
        SELECT 'PRIEST' CLASS, 3 GRADE, 1 IDX, UTL_RAW.CAST_TO_VARCHAR2(HEXTORAW('BEC6BBE7C8F7')) NM FROM DUAL UNION ALL
        SELECT 'PRIEST' CLASS, 3 GRADE, 2 IDX, UTL_RAW.CAST_TO_VARCHAR2(HEXTORAW('B7BBB0D4')) NM FROM DUAL UNION ALL
        SELECT 'PRIEST' CLASS, 4 GRADE, 0 IDX, UTL_RAW.CAST_TO_VARCHAR2(HEXTORAW('C4DAC7CFB7E7')) NM FROM DUAL UNION ALL
        SELECT 'PRIEST' CLASS, 4 GRADE, 1 IDX, UTL_RAW.CAST_TO_VARCHAR2(HEXTORAW('B9CCB7B9C0CC')) NM FROM DUAL UNION ALL
        SELECT 'PRIEST' CLASS, 5 GRADE, 0 IDX, UTL_RAW.CAST_TO_VARCHAR2(HEXTORAW('BDBAC0CCB7BB')) NM FROM DUAL UNION ALL
        SELECT 'PRIEST' CLASS, 6 GRADE, 0 IDX, UTL_RAW.CAST_TO_VARCHAR2(HEXTORAW('BEC6B8B6B3D7')) NM FROM DUAL
    ) NP ON (NP.CLASS = R.CLASS AND NP.GRADE = R.GRADE AND NP.IDX = R.IDX)
) SRC
ON (C.COMPANION_ID = SRC.COMPANION_ID)
WHEN MATCHED THEN UPDATE SET C.NAME = SRC.NEW_NAME;

COMMIT;

-- Verify: no GRADE>=2 companion should still carry a GRADE=1-only name after this.
SELECT CLASS, GRADE, NAME, COUNT(*) CNT
FROM TBOT_S5_USER_COMPANION
WHERE GRADE >= 2
GROUP BY CLASS, GRADE, NAME
ORDER BY CLASS, GRADE, NAME;

EXIT;
