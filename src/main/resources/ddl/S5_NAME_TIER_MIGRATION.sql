        SELECT 'ROGUE' CLASS, 3 GRADE, 0 IDX, UTL_RAW.CAST_TO_VARCHAR2(HEXTORAW('B7B9C0CC')) NM FROM DUAL UNION ALL
        SELECT 'ROGUE' CLASS, 3 GRADE, 1 IDX, UTL_RAW.CAST_TO_VARCHAR2(HEXTORAW('BEC6C5B0B6F3')) NM FROM DUAL UNION ALL
        SELECT 'ROGUE' CLASS, 3 GRADE, 2 IDX, UTL_RAW.CAST_TO_VARCHAR2(HEXTORAW('BCD2B8B6')) NM FROM DUAL UNION ALL
        SELECT 'ROGUE' CLASS, 4 GRADE, 0 IDX, UTL_RAW.CAST_TO_VARCHAR2(HEXTORAW('C0AFC0CCC5E4')) NM FROM DUAL UNION ALL
        SELECT 'ROGUE' CLASS, 4 GRADE, 1 IDX, UTL_RAW.CAST_TO_VARCHAR2(HEXTORAW('C4ABB0D4B7CEBFEC')) NM FROM DUAL UNION ALL
        SELECT 'ROGUE' CLASS, 5 GRADE, 0 IDX, UTL_RAW.CAST_TO_VARCHAR2(HEXTORAW('B3AAB1E2')) NM FROM DUAL UNION ALL
