        SELECT 'WARRIOR' CLASS, 3 GRADE, 0 IDX, UTL_RAW.CAST_TO_VARCHAR2(HEXTORAW('C7CFBEDFC5E4')) NM FROM DUAL UNION ALL
        SELECT 'WARRIOR' CLASS, 3 GRADE, 1 IDX, UTL_RAW.CAST_TO_VARCHAR2(HEXTORAW('C4DAC5B8B7CE')) NM FROM DUAL UNION ALL
        SELECT 'WARRIOR' CLASS, 3 GRADE, 2 IDX, UTL_RAW.CAST_TO_VARCHAR2(HEXTORAW('C1F8')) NM FROM DUAL UNION ALL
        SELECT 'WARRIOR' CLASS, 4 GRADE, 0 IDX, UTL_RAW.CAST_TO_VARCHAR2(HEXTORAW('B7BBC1F6')) NM FROM DUAL UNION ALL
        SELECT 'WARRIOR' CLASS, 4 GRADE, 1 IDX, UTL_RAW.CAST_TO_VARCHAR2(HEXTORAW('BEC6C3F7BDC3')) NM FROM DUAL UNION ALL
        SELECT 'WARRIOR' CLASS, 5 GRADE, 0 IDX, UTL_RAW.CAST_TO_VARCHAR2(HEXTORAW('C3F7BFE4BDC3')) NM FROM DUAL UNION ALL
        SELECT 'WARRIOR' CLASS, 6 GRADE, 0 IDX, UTL_RAW.CAST_TO_VARCHAR2(HEXTORAW('B0EDBFECC5B0')) NM FROM DUAL UNION ALL
        SELECT 'MAGE' CLASS, 2 GRADE, 0 IDX, UTL_RAW.CAST_TO_VARCHAR2(HEXTORAW('B9CCC0AF')) NM FROM DUAL UNION ALL
        SELECT 'MAGE' CLASS, 2 GRADE, 1 IDX, UTL_RAW.CAST_TO_VARCHAR2(HEXTORAW('B8AEBBE7')) NM FROM DUAL UNION ALL
        SELECT 'MAGE' CLASS, 2 GRADE, 2 IDX, UTL_RAW.CAST_TO_VARCHAR2(HEXTORAW('B3AABFC0')) NM FROM DUAL UNION ALL
        SELECT 'MAGE' CLASS, 3 GRADE, 0 IDX, UTL_RAW.CAST_TO_VARCHAR2(HEXTORAW('BBE7BEDF')) NM FROM DUAL UNION ALL
        SELECT 'MAGE' CLASS, 3 GRADE, 1 IDX, UTL_RAW.CAST_TO_VARCHAR2(HEXTORAW('B8B6C0CC')) NM FROM DUAL UNION ALL
        SELECT 'MAGE' CLASS, 3 GRADE, 2 IDX, UTL_RAW.CAST_TO_VARCHAR2(HEXTORAW('C0AFB3AA')) NM FROM DUAL UNION ALL
        SELECT 'MAGE' CLASS, 4 GRADE, 0 IDX, UTL_RAW.CAST_TO_VARCHAR2(HEXTORAW('B8AEBFC0')) NM FROM DUAL UNION ALL
        SELECT 'MAGE' CLASS, 4 GRADE, 1 IDX, UTL_RAW.CAST_TO_VARCHAR2(HEXTORAW('C4ABB3AA')) NM FROM DUAL UNION ALL
        SELECT 'MAGE' CLASS, 5 GRADE, 0 IDX, UTL_RAW.CAST_TO_VARCHAR2(HEXTORAW('B9CCC4DAC5E4')) NM FROM DUAL UNION ALL
        SELECT 'MAGE' CLASS, 6 GRADE, 0 IDX, UTL_RAW.CAST_TO_VARCHAR2(HEXTORAW('BCBCB6F3')) NM FROM DUAL UNION ALL
        SELECT 'ROGUE' CLASS, 2 GRADE, 0 IDX, UTL_RAW.CAST_TO_VARCHAR2(HEXTORAW('BDC5C1F6')) NM FROM DUAL UNION ALL
