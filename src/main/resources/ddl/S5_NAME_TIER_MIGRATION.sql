        SELECT 'ARCHER' CLASS, 2 GRADE, 1 IDX, UTL_RAW.CAST_TO_VARCHAR2(HEXTORAW('B9CCBBE7C5B0')) NM FROM DUAL UNION ALL
        SELECT 'ARCHER' CLASS, 2 GRADE, 2 IDX, UTL_RAW.CAST_TO_VARCHAR2(HEXTORAW('C0AFC1EEC5B0')) NM FROM DUAL UNION ALL
        SELECT 'ARCHER' CLASS, 3 GRADE, 0 IDX, UTL_RAW.CAST_TO_VARCHAR2(HEXTORAW('B8AEC4DA')) NM FROM DUAL UNION ALL
        SELECT 'ARCHER' CLASS, 3 GRADE, 1 IDX, UTL_RAW.CAST_TO_VARCHAR2(HEXTORAW('B8B6C0AF')) NM FROM DUAL UNION ALL
        SELECT 'ARCHER' CLASS, 3 GRADE, 2 IDX, UTL_RAW.CAST_TO_VARCHAR2(HEXTORAW('C7CFB7E7C4AB')) NM FROM DUAL UNION ALL
        SELECT 'ARCHER' CLASS, 4 GRADE, 0 IDX, UTL_RAW.CAST_TO_VARCHAR2(HEXTORAW('BCBCB8AEB3AA')) NM FROM DUAL UNION ALL
