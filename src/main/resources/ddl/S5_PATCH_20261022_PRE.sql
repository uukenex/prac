-- ============================================================
-- Season 5 patch 2026-10-22 -- PRE-DEPLOY (additive only; the currently running code ignores all of this).
--  1) TBOT_S5_USER_EQUIP.QTY: stack count. Unequipped non-legendary items of the same (USER_NAME, CLASS, PART, GRADE)
--     share one row with QTY = n. Equipped rows and legendary rows always keep QTY = 1. Default 1 = old behavior.
--     The rows are merged by S5_EQUIP_QTY_MERGE_POST.sql, which must run only AFTER the QTY-aware code is deployed.
--  2) TBOT_S5_USER_PROGRESS.PATCH_ACK_VERSION: the patch-notice version the user confirmed (dice are blocked until confirmed).
--  3) TBOT_S5_ENHANCE_TICKET (+ SEQ_S5_ENHANCE_TICKET): enhancement tickets returned when an enhanced legendary is dismantled.
-- ASCII-only file, safe to re-run.
-- ============================================================
DECLARE
    v_cnt NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_cnt FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'TBOT_S5_USER_EQUIP' AND COLUMN_NAME = 'QTY';
    IF v_cnt = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE TBOT_S5_USER_EQUIP ADD (QTY NUMBER DEFAULT 1 NOT NULL)';
    END IF;

    SELECT COUNT(*) INTO v_cnt FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'TBOT_S5_USER_PROGRESS' AND COLUMN_NAME = 'PATCH_ACK_VERSION';
    IF v_cnt = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE TBOT_S5_USER_PROGRESS ADD (PATCH_ACK_VERSION VARCHAR2(20) NULL)';
    END IF;

    SELECT COUNT(*) INTO v_cnt FROM USER_TABLES WHERE TABLE_NAME = 'TBOT_S5_ENHANCE_TICKET';
    IF v_cnt = 0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE TBOT_S5_ENHANCE_TICKET (TICKET_ID NUMBER PRIMARY KEY, USER_NAME VARCHAR2(100) NOT NULL, '
            || 'ENHANCE_LEVEL NUMBER NOT NULL, SOURCE_LEGENDARY_ID NUMBER NULL, INSERT_DATE DATE DEFAULT SYSDATE NOT NULL)';
        EXECUTE IMMEDIATE 'CREATE INDEX IDX_S5_ENH_TICKET_USER ON TBOT_S5_ENHANCE_TICKET (USER_NAME)';
    END IF;

    SELECT COUNT(*) INTO v_cnt FROM USER_SEQUENCES WHERE SEQUENCE_NAME = 'SEQ_S5_ENHANCE_TICKET';
    IF v_cnt = 0 THEN
        EXECUTE IMMEDIATE 'CREATE SEQUENCE SEQ_S5_ENHANCE_TICKET START WITH 1 INCREMENT BY 1 NOCACHE';
    END IF;
END;
/

SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, NULLABLE, DATA_DEFAULT FROM USER_TAB_COLUMNS
 WHERE (TABLE_NAME = 'TBOT_S5_USER_EQUIP' AND COLUMN_NAME = 'QTY') OR (TABLE_NAME = 'TBOT_S5_USER_PROGRESS' AND COLUMN_NAME = 'PATCH_ACK_VERSION');
SELECT COUNT(*) AS TICKET_TABLE FROM USER_TABLES WHERE TABLE_NAME = 'TBOT_S5_ENHANCE_TICKET';
SELECT COUNT(*) AS ROWS_QTY_NOT_1 FROM TBOT_S5_USER_EQUIP WHERE QTY <> 1;
EXIT;
