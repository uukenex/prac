-- "55층부터 소울주춤 유저 스펙 기준으로 일반 몬스터는 승률 50%, 강화몹(항상 정확히
-- 2배)은 승률 10%대(사실상 못 넘어갈 정도)로 스펙업해달라"는 요청. 이 계정 현재 파티
-- (나기 ROGUE ★5 -- 반격 대상 시 30% 회피/리오 MAGE ★4/코하루 PRIEST ★4, 장비+스탯구매
-- 반영 유효 ATK 151/130/65·DEF 39/27/45(★2/★3/★4/★5 장비 혼합)·HP 1134/371/567,
-- 파티 구성이 전부 다른 직업이라 "레인보우" 시너지(ATK/DEF +10%) 적용, DICE_12,
-- 51~70층 몬스터 전용 랜덤 주사위(6~12) 포함)를 기준으로 Node.js 몬테카를로 시뮬레이션.
--
-- 강화몹은 코드상 항상 정확히 일반 몬스터의 2배(HP/ATK/DEF)라 "일반 50%·강화 10%"를
-- 동시에 정확히 만족하는 조합은 존재하지 않음(강화 승률이 일반보다 훨씬 가파르게
-- 떨어짐) -- "강화몹은 거의 못 넘어갈 정도"라는 의도를 우선해서, 일반 몬스터 승률이
-- 정확히 50%에 가깝게 맞춰지는 조합을 선택(이때 강화 승률은 1% 미만으로 나옴).
--
-- 기존 5000/102/10(51층+ ATK 3배 적용 후 값) -> 13000/188/28. PP_PER_KILL은 건드리지 않음.
--
-- ASCII-only file, 재실행해도 안전(같은 값으로 재적용될 뿐).
-- ============================================================

UPDATE TBOT_S5_MONSTER_INFO
SET HP_VALUE = 13000, ATK_VALUE = 188, DEF_VALUE = 28
WHERE MONSTER_ID = 106;

COMMIT;

SELECT MONSTER_ID, BLOCK_NO, MONSTER_NAME, HP_VALUE, ATK_VALUE, DEF_VALUE, PP_PER_KILL_VALUE, BOSS_YN
FROM TBOT_S5_MONSTER_INFO WHERE BLOCK_NO = 6;
EXIT;
