-- [2026-11-18] 시즌 5.5(광산) 바다 낚시 -- "기록을 남기려면 s5.5로 복사해 와야겠다, 마이그레이션까지 하고 이후 별도로, CTAS로"
-- 시즌4 낚시 테이블을 그대로 복사(CTAS)해서 광산은 이 테이블들만 쓴다(시즌4와 따로 간다).
-- CTAS는 NOT NULL만 옮기므로 기본키/기본값/인덱스는 아래에서 다시 붙인다.
-- 낚시 기록(TBOT_S55_FISH_LOG)은 한 번 던질 때마다 한 줄(시즌4처럼 하루 한 줄이 아니다) -- 기본키 없이 유저 인덱스, MAP_ID(낚은 맵) 추가.

CREATE TABLE TBOT_S55_FISH_INFO AS SELECT * FROM TBOT_S4_FISH_INFO;
ALTER TABLE TBOT_S55_FISH_INFO ADD CONSTRAINT PK_S55_FISH_INFO PRIMARY KEY (FISH_ID);
ALTER TABLE TBOT_S55_FISH_INFO MODIFY (ACTIVE_YN DEFAULT '1', REG_DATE DEFAULT SYSDATE);

CREATE TABLE TBOT_S55_FISH_EQUIP AS SELECT * FROM TBOT_S4_USER_EQUIP;
ALTER TABLE TBOT_S55_FISH_EQUIP ADD CONSTRAINT PK_S55_FISH_EQUIP PRIMARY KEY (USER_NAME);
ALTER TABLE TBOT_S55_FISH_EQUIP MODIFY (ROD_GRADE DEFAULT 1, BOBBER_GRADE DEFAULT 1, REG_DATE DEFAULT SYSDATE);

CREATE TABLE TBOT_S55_FISH_INV AS SELECT * FROM TBOT_S4_FISH_INV;
ALTER TABLE TBOT_S55_FISH_INV ADD CONSTRAINT PK_S55_FISH_INV PRIMARY KEY (USER_NAME, FISH_ID);
ALTER TABLE TBOT_S55_FISH_INV MODIFY (QTY DEFAULT 0);

CREATE TABLE TBOT_S55_FISH_ACH AS SELECT * FROM TBOT_S4_ACHIEVEMENT;
ALTER TABLE TBOT_S55_FISH_ACH ADD CONSTRAINT PK_S55_FISH_ACH PRIMARY KEY (ACH_ID);

CREATE TABLE TBOT_S55_FISH_USER_ACH AS SELECT * FROM TBOT_S4_USER_ACH;
ALTER TABLE TBOT_S55_FISH_USER_ACH ADD CONSTRAINT PK_S55_FISH_USER_ACH PRIMARY KEY (USER_NAME, ACH_ID);
ALTER TABLE TBOT_S55_FISH_USER_ACH MODIFY (CLEAR_DATE DEFAULT SYSDATE);

CREATE TABLE TBOT_S55_FISH_LOG AS SELECT USER_NAME, FISHING_DATE, FISH_ID, INSERT_DATE, CAST(NULL AS VARCHAR2(30)) AS MAP_ID FROM TBOT_S4_FISHING_LOG;
ALTER TABLE TBOT_S55_FISH_LOG MODIFY (INSERT_DATE DEFAULT SYSDATE);
CREATE INDEX IX_S55_FISH_LOG_USER ON TBOT_S55_FISH_LOG (USER_NAME);
