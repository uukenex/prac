-- Season 5 - 51층 이후 몬스터/보스 ATK 3배 상향 ("51층부터 데미지 3배로
-- 늘려줘" 요청, 2026-09-06)
-- 이미 배포된 DB(TBOT_S5_MONSTER_INFO에 106~110/206~210 로우가 존재)에
-- 실행하는 UPDATE 스크립트. HP/DEF/PP_PER_KILL은 그대로 두고 ATK_VALUE만
-- 3배로 올린다. ASCII 리터럴만 사용하므로(숫자 컬럼만 갱신) NLS_LANG 인코딩
-- 문제와는 무관 -- 조회(SELECT)만 할 때와 마찬가지로
-- `export NLS_LANG=KOREAN_KOREA.AL32UTF8` 정도면 충분.
--
-- S5_MASTER_DATA.sql의 INSERT 문도 동일한 값으로 함께 갱신해뒀으니, 신규로
-- 처음부터 세팅하는 환경이면 이 파일은 실행할 필요 없음.
--
-- 대상 범위: 51층 이후 전 구간(블록6~10, 51~100층) = 일반 몬스터 106~110,
-- 보스 206~210. 51~60층 몬스터(106번)의 원래 ATK 34가 "너무 낮다"는 확인
-- 과정에서 나온 요청이라, 이번 재산정(S5_TOWER_DESIGN.md 참고)의 51~78층
-- 구간뿐 아니라 그 이후 미조정 구간(81~100층, 109/110/209/210)까지 전부
-- 포함한다.
-- ============================================================

UPDATE TBOT_S5_MONSTER_INFO SET ATK_VALUE = ATK_VALUE * 3 WHERE MONSTER_ID IN (106, 107, 108, 109, 110, 206, 207, 208, 209, 210);

COMMIT;

-- 적용 결과 확인용 (원래 값과 비교: 106=34->102, 107=29->87, 108=37->111,
-- 109=2400->7200, 110=5000->15000, 206=75->225, 207=64->192, 208=81->243,
-- 209=5280->15840, 210=11000->33000)
SELECT MONSTER_ID, BLOCK_NO, MONSTER_NAME, ATK_VALUE, BOSS_YN
FROM TBOT_S5_MONSTER_INFO
WHERE MONSTER_ID IN (106, 107, 108, 109, 110, 206, 207, 208, 209, 210)
ORDER BY BOSS_YN, BLOCK_NO;
EXIT;
