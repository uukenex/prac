  SELECT e.EQUIP_ID, e.PART, e.GRADE, e.LEGENDARY_ID,
         lm.EFFECT_TYPE AS LEGENDARY_EFFECT_TYPE, lm.EFFECT_PARAM1 AS LEGENDARY_EFFECT_PARAM1,
         lm.ITEM_NAME AS LEGENDARY_ITEM_NAME
    FROM TBOT_S5_USER_EQUIP e
