-- Season 5 - legendary robe #4 (2026-09-29): MAGE+PRIEST robe (ROBE/ARMOR),
-- START_BARRIER: wearer starts each combat with a one-time invulnerability
-- ward (next hit fully negated). Name = "enigma" (Korean word, CP949 hex).
-- EFFECT_PARAM1 unused (NOT NULL column -> 1). Idempotent.
